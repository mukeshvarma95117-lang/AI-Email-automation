CREATE POLICY "Public full access contacts" ON public.contacts FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public full access messages" ON public.messages;
CREATE POLICY "Public full access messages" ON public.messages FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public full access scheduled_messages" ON public.scheduled_messages;
CREATE POLICY "Public full access scheduled_messages" ON public.scheduled_messages FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public full access message_logs" ON public.message_logs;
CREATE POLICY "Public full access message_logs" ON public.message_logs FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public full access settings" ON public.settings;
CREATE POLICY "Public full access settings" ON public.settings FOR ALL USING (true) WITH CHECK (true);

