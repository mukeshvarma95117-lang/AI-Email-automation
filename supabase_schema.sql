-- 1. Groups Table
CREATE TABLE IF NOT EXISTS public.groups_table (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  description TEXT,
  color TEXT DEFAULT '#6366F1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Contacts Table
CREATE TABLE IF NOT EXISTS public.contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT,
  phone TEXT,
  group_id BIGINT REFERENCES public.groups_table(id) ON DELETE SET NULL,
  custom_fields JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Messages Table
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  prompt TEXT,
  subject TEXT,
  body TEXT NOT NULL,
  short_version TEXT,
  cta TEXT,
  channel TEXT NOT NULL DEFAULT 'email',
  recipient_count INTEGER DEFAULT 0,
  recipients_json TEXT DEFAULT '[]',
  status TEXT DEFAULT 'sent',
  is_demo INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Scheduled Messages Table
CREATE TABLE IF NOT EXISTS public.scheduled_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT REFERENCES public.messages(id) ON DELETE CASCADE,
  channel TEXT NOT NULL DEFAULT 'email',
  subject TEXT,
  body TEXT NOT NULL,
  recipients_json TEXT DEFAULT '[]',
  scheduled_time TIMESTAMPTZ NOT NULL,
  timezone TEXT DEFAULT 'UTC',
  status TEXT DEFAULT 'scheduled',
  is_demo INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Message Delivery Logs Table
CREATE TABLE IF NOT EXISTS public.message_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT,
  contact_id BIGINT,
  contact_name TEXT,
  contact_target TEXT,
  channel TEXT NOT NULL DEFAULT 'email',
  rendered_subject TEXT,
  rendered_body TEXT NOT NULL,
  status TEXT NOT NULL,
  is_demo INTEGER DEFAULT 1,
  error_message TEXT,
  delivery_timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Settings Table
CREATE TABLE IF NOT EXISTS public.settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT UNIQUE NOT NULL,
  value TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

